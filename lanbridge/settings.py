"""Typed configuration for LanBridge, loaded from a TOML file.

Only the standard library is used (tomllib, Python 3.11+). Missing keys fall
back to the defaults below, so a two-line config file is valid.
"""

from __future__ import annotations

import ipaddress
import tomllib
from dataclasses import asdict, dataclass, field, fields
from pathlib import Path
from typing import Any

CONFIG_NAME = "lanbridge.toml"


@dataclass
class Site:
    name: str = "lab-ap"
    subnet: str = "192.168.50.0/24"
    gateway: str = "192.168.50.1"
    dhcp_start: str = "192.168.50.200"
    dhcp_end: str = "192.168.50.219"
    bridge_address: str = "192.168.50.240"


@dataclass
class Tunnel:
    transport: str = "softether"          # softether | openvpn | vxlan
    remote_host: str = "203.0.113.10"
    listen_port: int = 1194
    remote_port: int = 1194
    mtu: int = 1500

    # WireGuard/VXLAN underlay (Linux only).
    wg_port: int = 51820
    wg_host_ip: str = "10.99.0.1"
    wg_client_ip: str = "10.99.0.2"
    vxlan_id: int = 42
    vxlan_port: int = 4789


@dataclass
class Host:
    lan_iface: str = "eth0"
    tap_iface: str = "tap0"
    bridge_iface: str = "br0"
    wg_iface: str = "wg0"
    vxlan_iface: str = "vxlan42"


@dataclass
class Client:
    static_ip: str = "192.168.50.77"
    tap_iface: str = "tap0"
    vpn_adapter_name: str = "LanBridge"


@dataclass
class Settings:
    site: Site = field(default_factory=Site)
    tunnel: Tunnel = field(default_factory=Tunnel)
    host: Host = field(default_factory=Host)
    client: Client = field(default_factory=Client)

    # --- derived values ---------------------------------------------------
    @property
    def network(self) -> ipaddress.IPv4Network:
        return ipaddress.IPv4Network(self.site.subnet, strict=False)

    @property
    def netmask(self) -> str:
        return str(self.network.netmask)

    @property
    def prefixlen(self) -> int:
        return self.network.prefixlen

    @property
    def broadcast(self) -> str:
        return str(self.network.broadcast_address)

    @property
    def network_address(self) -> str:
        return str(self.network.network_address)

    # MTU budget for the Linux VXLAN path.
    @property
    def wg_mtu(self) -> int:
        return 1420

    @property
    def vxlan_mtu(self) -> int:
        # VXLAN on top of WireGuard: 14 (inner eth) + 8 (vxlan) + 8 (udp)
        # + 20 (outer ipv4) = 50 bytes of encapsulation.
        return self.wg_mtu - 50

    # --- serialisation ----------------------------------------------------
    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def save(self, path: Path) -> Path:
        path.write_text(dumps(self), encoding="utf-8")
        return path

    @classmethod
    def load(cls, path: Path) -> "Settings":
        if not path.exists():
            return cls()
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        return cls.from_dict(data)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Settings":
        cfg = cls()
        for section in fields(cls):
            values = data.get(section.name)
            if not isinstance(values, dict):
                continue
            target = getattr(cfg, section.name)
            for key, value in values.items():
                if not hasattr(target, key):
                    continue
                current = getattr(target, key)
                # TOML has no implicit int->str casts; keep the field's type.
                if isinstance(current, int) and not isinstance(value, bool):
                    try:
                        value = int(value)
                    except (TypeError, ValueError):
                        continue
                elif isinstance(current, str):
                    value = str(value)
                setattr(target, key, value)
        return cfg


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def dumps(cfg: Settings) -> str:
    """Render settings back to TOML (comments are not preserved)."""
    lines = ["# LanBridge configuration (regenerated by `lanbridge`)"]
    for section in ("site", "tunnel", "host", "client"):
        lines += ["", f"[{section}]"]
        for key, value in asdict(getattr(cfg, section)).items():
            lines.append(f"{key} = {_toml_value(value)}")
    return "\n".join(lines) + "\n"


def find_config(start: Path) -> Path:
    """Look for lanbridge.toml in ./ , ./examples and the repo root."""
    candidates = [
        start / CONFIG_NAME,
        start / "examples" / CONFIG_NAME,
        Path(__file__).resolve().parent.parent / CONFIG_NAME,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return start / CONFIG_NAME
